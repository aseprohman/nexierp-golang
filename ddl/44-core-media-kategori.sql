-- =============================================================================
-- PATCH DDL 44-core-media-kategori.sql — Struktur media library v2
-- Domain   : CORE — media library terpusat (core_files) + kategori dokumen/
--            multimedia per modul (core_media_categories — tabel BARU).
-- Sumber   : keputusan pemilik 2026-11-08 — core_files ditambah FK ke
--            core_modules & FK ke core_media_categories; library FE+BE
--            mengikuti struktur baru (filter modul/kategori, soft delete).
-- Tanggal  : 2026-11-08
-- Prasyarat: baseline core (tabel core_files, core_modules live).
-- Isi      : §1 tabel core_media_categories [MASTER]; §2 refactor core_files
--            (2 FK baru + trio audit + version + soft delete; 6 kolom text →
--            varchar bucket — diukur max(length) live); §3 index; §4 seed
--            kategori contoh idempoten.
-- Makna    : hapus kategori = SOFT DELETE + media terkait di-SET NULL
--            (menjadi "Tanpa kategori") — aset TIDAK pernah ikut terhapus.
--            hapus file = soft delete (konsumen FK RESTRICT ecom/fin/hr
--            selamat; object MinIO dibersihkan sweep terpisah).
-- Idempoten: IF NOT EXISTS / IF EXISTS / DO-guard di semua statement;
--            seed WHERE NOT EXISTS by (nama, id_core_modules).
-- =============================================================================

BEGIN;

-- =============================================================================
-- §1 [MASTER] core_media_categories — kategori dokumen/multimedia per modul
--    Pemilik: core (system-files). NULL id_core_modules = kategori lintas
--    modul (bersama). Trio audit + version (mutasi via API, optimistic lock).
-- =============================================================================
CREATE TABLE IF NOT EXISTS core_media_categories (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id         uuid NOT NULL,
  id_core_modules   bigint REFERENCES core_modules (id)
                      ON UPDATE CASCADE ON DELETE SET NULL,
  nama              varchar(100) NOT NULL,
  keterangan        varchar(200),
  version           integer NOT NULL DEFAULT 1,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  CONSTRAINT uq_core_media_categories_entity_id UNIQUE (entity_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_core_media_categories_nama
  ON core_media_categories (coalesce(id_core_modules, 0), nama)
  WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS ix_core_media_categories_modul
  ON core_media_categories (id_core_modules) WHERE deleted_at IS NULL;

-- =============================================================================

-- =============================================================================
-- §2 [MASTER/ASSET] refactor core_files — FK modul & kategori + trio audit +
--    version + soft delete; tipe teks ke bucket varchar (ukuran diukur live:
--    bucket≤7, object_key≤86, original_name≤39, mime_type≤15, scope≤11).
-- =============================================================================
ALTER TABLE core_files
  ADD COLUMN IF NOT EXISTS id_core_modules bigint
    REFERENCES core_modules (id) ON UPDATE CASCADE ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS id_core_media_categories bigint
    REFERENCES core_media_categories (id) ON UPDATE CASCADE ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS version integer NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS deleted_at timestamptz;

-- Backfill trio — updated_at mengikuti created_at (idempoten: nilai sama).
UPDATE core_files SET updated_at = created_at;

-- Tipe teks → bucket varchar (idempoten: re-ALTER ke tipe sama = no-op data).
ALTER TABLE core_files
  ALTER COLUMN bucket        TYPE varchar(50),
  ALTER COLUMN object_key    TYPE varchar(300),
  ALTER COLUMN original_name TYPE varchar(300),
  ALTER COLUMN mime_type     TYPE varchar(100),
  ALTER COLUMN scope         TYPE varchar(50),
  ALTER COLUMN checksum_sha256 TYPE varchar(64);

-- =============================================================================

-- =============================================================================
-- §3 index pendukung query library (filter modul/kategori + baca hidup)
-- =============================================================================
CREATE INDEX IF NOT EXISTS ix_core_files_modul
  ON core_files (id_core_modules) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_core_files_kategori
  ON core_files (id_core_media_categories) WHERE deleted_at IS NULL;

-- =============================================================================

-- =============================================================================
-- §4 seed kategori contoh — idempoten (WHERE NOT EXISTS by nama+modul).
--    Global (NULL modul) = bersama lintas modul; sisanya milik modul
--    pemakai media yang sudah live (hr/fin/ecom).
-- =============================================================================
INSERT INTO core_media_categories (entity_id, id_core_modules, nama, keterangan)
SELECT gen_random_uuid(), NULL, v.nama, v.ket
FROM (VALUES
  ('Dokumen Umum',     'Dokumen kebijakan, SOP & surat menyurat lintas modul'),
  ('Gambar & Grafis',  'Logo, banner & aset gambar bersama')
) AS v(nama, ket)
WHERE NOT EXISTS (
  SELECT 1 FROM core_media_categories c
  WHERE c.nama = v.nama AND c.id_core_modules IS NULL AND c.deleted_at IS NULL
);

INSERT INTO core_media_categories (entity_id, id_core_modules, nama, keterangan)
SELECT gen_random_uuid(), m.id, v.nama, v.ket
FROM (VALUES
  ('hr',  'Dokumen Karyawan',   'FC, KTP, ijazah & dokumen kepegawaian'),
  ('fin', 'Lampiran Keuangan',  'Bukti transfer, invoice & kwitansi'),
  ('ecom','Media Katalog',      'Foto produk & aset katalog online')
) AS v(modul_key, nama, ket)
JOIN core_modules m ON m.key::text = v.modul_key
WHERE NOT EXISTS (
  SELECT 1 FROM core_media_categories c
  WHERE c.nama = v.nama AND c.id_core_modules = m.id AND c.deleted_at IS NULL
);

COMMIT;

-- =============================================================================
-- VERIFIKASI (harus 0 / sesuai)
-- =============================================================================
SELECT 'cek 1 kolom core_files' AS cek, count(*) FROM pg_attribute a
JOIN pg_class t ON t.oid = a.attrelid
WHERE t.relname = 'core_files' AND a.attisdropped = false
  AND a.attname IN ('id_core_modules','id_core_media_categories','version','updated_at','deleted_at');
SELECT 'cek 2 tabel kategori' AS cek, count(*) FROM pg_class
WHERE relname = 'core_media_categories' AND relkind = 'r';
SELECT 'cek 3 seed kategori' AS cek, count(*) FROM core_media_categories WHERE deleted_at IS NULL;
SELECT 'cek 4 tipe kolom' AS cek, count(*) FROM pg_attribute a
JOIN pg_class t ON t.oid = a.attrelid
WHERE t.relname = 'core_files' AND a.attisdropped = false
  AND ((a.attname = 'bucket' AND atttypmod <> 50 + 4)
    OR (a.attname = 'mime_type' AND atttypmod <> 100 + 4)
    OR (a.attname = 'object_key' AND atttypmod <> 300 + 4));

