-- ---- TABEL (IF NOT EXISTS, kolom persis live) ----
CREATE TABLE IF NOT EXISTS public.core_files (
    id bigint NOT NULL,
    entity_id uuid NOT NULL,
    bucket character varying(50) NOT NULL,
    object_key character varying(300) NOT NULL,
    original_name character varying(300) NOT NULL,
    mime_type character varying(100) NOT NULL,
    size_bytes bigint NOT NULL,
    checksum_sha256 character varying(64),
    scope character varying(50) DEFAULT 'general'::text NOT NULL,
    id_core_users bigint,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    id_core_modules bigint,
    id_core_media_categories bigint,
    version integer DEFAULT 1 NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    deleted_at timestamp with time zone,
    CONSTRAINT core_files_size_check CHECK ((size_bytes >= 0))
);

-- kolom identity (persis live; setelah tabel, dilewati bila sudah identity)
-- +goose StatementBegin
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_schema='public' AND table_name='core_files'
                   AND column_name='id' AND is_identity='YES') THEN
    ALTER TABLE public.core_files ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.core_files_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
  END IF;
EXCEPTION WHEN duplicate_object THEN NULL; WHEN duplicate_table THEN NULL; END $$;
-- +goose StatementEnd


