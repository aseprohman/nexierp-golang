-- enum dipakai kolom tabel live-only ini (kosakata persis live)
-- +goose StatementBegin
DO $$ BEGIN
  CREATE TYPE public.core_outbox_status AS ENUM (
    'pending',
    'delivered',
    'failed'
);
EXCEPTION WHEN duplicate_object THEN NULL; WHEN duplicate_table THEN NULL; END $$;
-- +goose StatementEnd


-- ---- TABEL (IF NOT EXISTS, kolom persis live) ----
CREATE TABLE IF NOT EXISTS public.core_outbox_events (
    id bigint NOT NULL,
    topic character varying(78) NOT NULL,
    payload jsonb DEFAULT '{}'::jsonb NOT NULL,
    status public.core_outbox_status DEFAULT 'pending'::public.core_outbox_status NOT NULL,
    available_at timestamp with time zone DEFAULT now() NOT NULL,
    attempts integer DEFAULT 0 NOT NULL,
    last_error character varying(30),
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    processed_at timestamp with time zone,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT core_outbox_events_attempts_check CHECK ((attempts >= 0))
);

-- kolom identity (persis live; setelah tabel, dilewati bila sudah identity)
-- +goose StatementBegin
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_schema='public' AND table_name='core_outbox_events'
                   AND column_name='id' AND is_identity='YES') THEN
    ALTER TABLE public.core_outbox_events ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.core_outbox_events_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
  END IF;
EXCEPTION WHEN duplicate_object THEN NULL; WHEN duplicate_table THEN NULL; END $$;
-- +goose StatementEnd


-- ---- CONSTRAINT (FK/PK/UNIQUE/CHECK persis live; idempoten) ----
-- +goose StatementBegin
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'core_outbox_events_pkey'
                 AND conrelid = 'public.core_outbox_events'::regclass) THEN
    ALTER TABLE ONLY public.core_outbox_events
    ADD CONSTRAINT core_outbox_events_pkey PRIMARY KEY (id);
  END IF;
EXCEPTION WHEN duplicate_object THEN NULL; WHEN duplicate_table THEN NULL; END $$;
-- +goose StatementEnd


-- ---- INDEX (persis live; IF NOT EXISTS) ----
CREATE INDEX IF NOT EXISTS core_outbox_events_available_at_idx ON public.core_outbox_events USING btree (available_at);

CREATE INDEX IF NOT EXISTS core_outbox_events_poll_idx ON public.core_outbox_events USING btree (available_at) WHERE (status = 'pending'::public.core_outbox_status);

CREATE INDEX IF NOT EXISTS core_outbox_events_status_idx ON public.core_outbox_events USING btree (status);

CREATE INDEX IF NOT EXISTS core_outbox_events_topic_idx ON public.core_outbox_events USING btree (topic);

CREATE UNIQUE INDEX IF NOT EXISTS uq_outbox_topic_key_pending ON public.core_outbox_events USING btree (topic, COALESCE((payload ->> '_key'::text), ''::text)) WHERE ((status = ANY (ARRAY['pending'::public.core_outbox_status, 'delivered'::public.core_outbox_status])) AND (payload ? '_key'::text));